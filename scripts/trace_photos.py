"""Trace the main structural lines of every photo in public/images.

Writes lib/photo-traces.ts, used by components/BuildImg.tsx to draw each photo
as an architectural elevation (sized to the photo's own width and height)
before the photo appears. Lines are ordered ground-up: foundation first,
roof last.

Run after adding or replacing photos:
    pip install opencv-python-headless pillow numpy
    python scripts/trace_photos.py
"""
import glob, json, os
import cv2
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_LINES = 60

def trace(path):
    im = Image.open(path).convert('RGB')
    W, H = im.size
    g = cv2.GaussianBlur(cv2.cvtColor(np.array(im), cv2.COLOR_RGB2GRAY), (5, 5), 0)
    segs = cv2.createLineSegmentDetector(cv2.LSD_REFINE_STD).detect(g)[0]
    segs = [] if segs is None else segs.reshape(-1, 4)
    diag = (W * W + H * H) ** 0.5
    keep = []
    for x1, y1, x2, y2 in sorted(segs, key=lambda s: -np.hypot(s[2] - s[0], s[3] - s[1])):
        if np.hypot(x2 - x1, y2 - y1) < diag * 0.06:
            break
        mx, my = (x1 + x2) / 2, (y1 + y2) / 2
        a = np.degrees(np.arctan2(y2 - y1, x2 - x1)) % 180
        dup = False
        for k in keep:  # skip near-duplicates of a line already kept
            b = np.degrees(np.arctan2(k[3] - k[1], k[2] - k[0])) % 180
            px, py = k[2] - k[0], k[3] - k[1]
            n = np.hypot(px, py)
            d = abs(px * (k[1] - my) - py * (k[0] - mx)) / n
            t = ((mx - k[0]) * px + (my - k[1]) * py) / n / n
            if min(abs(a - b), 180 - abs(a - b)) < 6 and d < W * 0.015 and -0.2 < t < 1.2:
                dup = True
                break
        if not dup:
            keep.append((x1, y1, x2, y2))
        if len(keep) >= MAX_LINES:
            break
    keep.sort(key=lambda s: -max(s[1], s[3]))  # ground up
    return {'w': W, 'h': H, 'lines': [[round(float(v)) for v in s] for s in keep]}

out = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'public', 'images', '*.webp'))):
    out['/images/' + os.path.basename(f)] = trace(f)
    print(os.path.basename(f), out['/images/' + os.path.basename(f)]['w'], out['/images/' + os.path.basename(f)]['h'], len(out['/images/' + os.path.basename(f)]['lines']))

body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, separators=(",", ":"))}' for k, v in out.items())
ts = ('// Generated by scripts/trace_photos.py. Do not edit by hand.\n'
      '// Structural lines traced from each photo, in that photo\'s own pixels, ordered ground-up.\n'
      'export type PhotoTrace = { w: number; h: number; lines: number[][] };\n\n'
      'export const PHOTO_TRACES: Record<string, PhotoTrace> = {\n' + body + ',\n};\n')
open(os.path.join(ROOT, 'lib', 'photo-traces.ts'), 'w').write(ts)
